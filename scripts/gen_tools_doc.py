"""Generate docs/TOOLS.md from the contract snapshots (single source of truth).

Usage: uv run python scripts/gen_tools_doc.py [--check]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOTS = ROOT / "tests" / "contract" / "snapshots"
OUT = ROOT / "docs" / "TOOLS.md"
ORDER = ["portfolio", "marketplace", "workspace"]
AUTH = "Bearer token (Streamable HTTP), per-user scope"


def flag(ann: dict, key: str) -> str:
    return "yes" if ann.get(key) else "no"


def render() -> str:
    rows, details = [], []
    for name in ORDER:
        snap = json.loads((SNAPSHOTS / f"{name}.json").read_text(encoding="utf-8"))
        for t in snap["tools"]:
            ann = t["annotations"] or {}
            kind = "read" if ann.get("readOnlyHint") else "write"
            props = t["inputSchema"].get("properties", {})
            extras = ", ".join(x for x in ("idempotency_key", "dry_run") if x in props) or "-"
            rows.append(
                f"| `{t['name']}` | {name} | {kind} | {flag(ann, 'readOnlyHint')} | "
                f"{flag(ann, 'destructiveHint')} | {flag(ann, 'idempotentHint')} | "
                f"{flag(ann, 'openWorldHint')} | {extras} | {AUTH} |"
            )
            params = ", ".join(
                f"`{p}`" + ("*" if p in t["inputSchema"].get("required", []) else "") for p in props
            )
            first_line = (t["description"] or "").strip().split("\n")[0]
            details.append(f"- **`{t['name']}`** ({name}) — {first_line} Params: {params or '-'}")
        if snap["resource_templates"]:
            details.append(
                f"- **{name} resources:** "
                + ", ".join(f"`{u}`" for u in snap["resource_templates"])
            )
        if snap["prompts"]:
            details.append(
                f"- **{name} prompts:** " + ", ".join(f"`{p['name']}`" for p in snap["prompts"])
            )
    return f"""# MCP tools

> Generated by `scripts/gen_tools_doc.py` from `tests/contract/snapshots/*.json`. Do not edit by
> hand: change the server, run `make snapshots && make tools-doc`, commit together.

## Own servers

| Tool | Server | Read/write | readOnly | destructive | idempotent | openWorld | Safety params | Auth |
|---|---|---|---|---|---|---|---|---|
{chr(10).join(rows)}

\\* = required parameter.

{chr(10).join(details)}

### What the annotations mean here

- **readOnlyHint** - the tool never changes anything. Agents may call it freely.
- **destructiveHint** - the effect cannot be undone. Only `submit_proposal` (spends Connects and
  sends the proposal to the client). It runs only after a human approval via LangGraph `interrupt()`.
- **idempotentHint** - repeating the call with the same arguments has no extra effect. For writes
  this is guaranteed by the required `idempotency_key`: same key + same args returns the stored
  result (`replayed: true`); same key + different args is rejected (`idempotency_conflict`).
- **openWorldHint** - the tool talks to an external system (the marketplace). Portfolio and
  Workspace (local mock) are closed-world.
- **dry_run** - every write can preview exactly what would be sent (and its Connects cost)
  without sending anything. The approval panel shows this preview.

### Cross-cutting behaviour

- Auth: bearer token per user on Streamable HTTP (`MCP_TOKENS`); 401 without a valid token.
- Rate limit: per-user token bucket (`MCP_RATE_LIMIT_PER_MIN`, default 50/min, below GigSim's 60).
- Audit: every call appends `(ts, user, server, tool, args_masked, result_summary, status, trace_id)`
  to `gigbid.mcp_audit_log`; on Postgres a trigger rejects UPDATE/DELETE (append-only).
- Errors surface as `<code>: <message>` (`not_found`, `rate_limited`, `marketplace_unavailable`,
  `policy_violation`, `insufficient_connects`, `idempotency_conflict`, `conflict`, ...).
- Untrusted text (job descriptions, client messages) is returned as data and labelled as such
  in tool descriptions; injection defence is applied on the agent side (Phase 9).

## Third-party MCP servers (trust rationale)

| Server | Used for | Trust decision |
|---|---|---|
| **Upwork MCP** (official, `https://mcp.upwork.com/mcp`) | Live marketplace via the `upwork_live` adapter (Phase 10) | Official first-party server of the marketplace; OAuth 2.1 per user, tokens stored encrypted. Used **behind our own Marketplace server/port**, so agents never call it directly. Writes only create drafts after GigBid approval; the user confirms on Upwork. |
| **GitHub MCP** (GitHub's official server) | Ingesting the freelancer's real repositories into the portfolio (Phase 4) | Read-only use with a fine-grained, read-only token scoped to the user's chosen repos. Only the ingestion job calls it; no agent node gets GitHub tools. Content is treated as untrusted data. |
"""


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/TOOLS.md is out of date: run `make tools-doc`")
            return 1
        print("docs/TOOLS.md up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
